/**
 * The **Original FX** panel: a small, honest window onto the clean-room FX
 * generator in `@swl/art`.
 *
 * The frames are not fetched and are not copied from the original game. They
 * are produced at render time by the same pure, seeded generator that writes
 * `assets/original/fx/`, serialised into inline `data:image/svg+xml` sources.
 * A CSS keyframe animation cycles the frames of each sequence; with
 * `prefers-reduced-motion: reduce` only the first frame is shown.
 *
 * The panel owns no game state, sends no command, rolls nothing, grants
 * nothing and reads no price: it is a reading of a deterministic generator.
 * It is JSX-free so Node's native TypeScript stripper can load it in tests;
 * `React.createElement` is used directly instead of a JSX transform.
 */
import * as React from 'react';

import type { DialogContent } from '@swl/client';
import {
  CC0_NOTICE,
  FX_SEQUENCES,
  GENERATOR_NAME,
  GENERATOR_VERSION,
  LICENCE,
  ORIGINAL_WORK_STATEMENT,
  fxFramePath,
  fxFrameSvg,
} from '@swl/art/browser';

/** The one dialog's id for the FX panel. */
export const ORIGINAL_FX_DIALOG_ID = 'original-fx';

/** The heading shown in the dialog and on the launcher. */
export const ORIGINAL_FX_TITLE = 'Original FX';

/** The client's own words — never a value read from the network. */
export const ORIGINAL_FX_INTRO =
  'Two short original animations, generated here, in the browser, by the same ' +
  'seeded generator that writes assets/original/fx. Nothing is downloaded.';

/** The visible, short CC0 line, derived from the generator's own constants. */
export const ORIGINAL_FX_CC0_LINE =
  `${LICENCE} · ${GENERATOR_NAME} ${GENERATOR_VERSION} · original work, dedicated to the public domain.`;

/** How the animation is driven, in the panel's own words. */
export const ORIGINAL_FX_MOTION_NOTE =
  'CSS keyframes cycle the generated frames. Reduced-motion settings show a single still frame.';

/** The one dialog's descriptor for the FX panel. */
export function originalFxDialog(): DialogContent {
  return { id: ORIGINAL_FX_DIALOG_ID, kind: 'alert', title: ORIGINAL_FX_TITLE };
}

/** Encode generated SVG bytes as an inline image source. No file is read. */
export function fxDataUrl(svg: string): string {
  return `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`;
}

/** One generated frame, paired with the generator's own provenance path. */
export interface OriginalFxFrame {
  readonly index: number;
  /** The generator's output path, kept for provenance; never used as a URL. */
  readonly path: string;
  /** An inline data URL; the only value ever handed to an `img` source. */
  readonly src: string;
}

/** One generated sequence and all of its frames. */
export interface OriginalFxSequence {
  readonly id: string;
  readonly title: string;
  readonly description: string;
  readonly frameMs: number;
  readonly frames: readonly OriginalFxFrame[];
}

/**
 * Build the panel's sequences from the generator's pure frame functions.
 *
 * The list is a pure function of `FX_SEQUENCES`: same generator, same frames,
 * same order. Every `src` is an inline data URL derived from generated bytes,
 * so the panel cannot reach a file, a CDN or the original game's art.
 */
export function originalFxSequences(): readonly OriginalFxSequence[] {
  return FX_SEQUENCES.map((sequence) => ({
    id: sequence.id,
    title: sequence.title,
    description: sequence.description,
    frameMs: sequence.frameMs,
    frames: Array.from({ length: sequence.frames }, (_, index) => ({
      index,
      path: fxFramePath(sequence.id, index),
      src: fxDataUrl(fxFrameSvg(sequence.id, index)),
    })),
  }));
}

/** Build a React element without JSX, so the file is loadable by Node. */
const e = React.createElement;

/** The chrome launcher. It only publishes an open gesture. */
export function OriginalFxLauncher({
  onOpen,
}: {
  readonly onOpen: () => void;
}): React.JSX.Element {
  return e(
    'button',
    {
      className: 'swl-original-fx-launcher',
      type: 'button',
      onClick: onOpen,
      'data-swl-original-fx': 'launcher',
      'aria-label': ORIGINAL_FX_TITLE,
    },
    ORIGINAL_FX_TITLE,
    e('span', { className: 'swl-original-fx-launcher-count' }, String(FX_SEQUENCES.length)),
  );
}

/**
 * The panel body hosted by the one shared dialog. Each stage stacks every
 * generated frame; `swl-original-fx-frame` and its keyframes do the cycling,
 * and the reduced-motion rule leaves only the first frame visible.
 */
export function OriginalFxGallery({
  onClose,
}: {
  readonly onClose: () => void;
}): React.JSX.Element {
  const sequences = originalFxSequences();
  return e(
    'section',
    { className: 'swl-original-fx', 'data-swl-original-fx': 'gallery' },
    e('h3', { className: 'swl-original-fx-heading' }, ORIGINAL_FX_TITLE),
    e('p', { className: 'swl-original-fx-intro' }, ORIGINAL_FX_INTRO),
    e(
      'ul',
      { className: 'swl-original-fx-list' },
      ...sequences.map((sequence) =>
        e(
          'li',
          {
            key: sequence.id,
            className: 'swl-original-fx-sequence',
            'data-swl-fx-sequence': sequence.id,
          },
          e(
            'div',
            {
              className: 'swl-original-fx-stage',
              'data-swl-fx-stage': sequence.id,
              role: 'img',
              'aria-label': sequence.title,
            },
            ...sequence.frames.map((frame) =>
              e('img', {
                key: frame.path,
                className: 'swl-original-fx-frame',
                src: frame.src,
                alt: frame.index === 0 ? sequence.title : '',
                title: frame.path,
                width: 64,
                height: 64,
                'data-swl-fx-frame': String(frame.index),
                'data-swl-fx-first': frame.index === 0 ? 'true' : 'false',
                'data-swl-art-generated': 'true',
                'aria-hidden': frame.index === 0 ? undefined : 'true',
              }),
            ),
          ),
          e('span', { className: 'swl-original-fx-name' }, sequence.title),
          e(
            'span',
            { className: 'swl-original-fx-detail' },
            `${sequence.frames.length} frames · ${sequence.frameMs} ms each`,
          ),
        ),
      ),
    ),
    e('p', { className: 'swl-original-fx-motion' }, ORIGINAL_FX_MOTION_NOTE),
    e(
      'p',
      {
        className: 'swl-original-fx-licence',
        'data-swl-fx-licence': LICENCE,
      },
      ORIGINAL_FX_CC0_LINE,
    ),
    e(
      'details',
      { className: 'swl-original-fx-details' },
      e('summary', null, 'Provenance and licence'),
      e('pre', { className: 'swl-original-fx-notice' }, CC0_NOTICE),
      e('p', { className: 'swl-original-fx-statement' }, ORIGINAL_WORK_STATEMENT),
    ),
    e(
      'button',
      {
        className: 'swl-original-fx-close',
        type: 'button',
        onClick: onClose,
        'data-swl-original-fx': 'close',
      },
      'Close',
    ),
  );
}
