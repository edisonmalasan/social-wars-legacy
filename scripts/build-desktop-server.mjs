#!/usr/bin/env node
/**
 * Build the desktop shell's server sidecar.
 *
 * A packaged shell may not assume `node` is on the player's PATH, and it
 * has no source repository to run scripts from. So the sidecar is the
 * project's own Node runtime plus a **self-contained copy** of the server,
 * with its TypeScript stripped to `.mjs` at build time:
 *
 * - `src-tauri/binaries/swl-server-<triple>[.exe]` — a copy of the Node
 *   binary used to build it. Tauri bundles it as `bundle.externalBin`,
 *   which places it beside the application's executable.
 * - `src-tauri/server/runtime/` — the server entry, the three workspace
 *   packages it imports, the content bundle, and its one external
 *   dependency (`@electric-sql/pglite`).
 *
 * Nothing is fetched and no new dependency is introduced: Node's own
 * `stripTypeScriptTypes` does the transform, and every file is copied
 * from this workspace. The copy is deliberately explicit — see
 * `src-tauri/server/README.md` — because a sidecar that silently depends
 * on the repository is not a sidecar.
 *
 * Usage:
 *   node scripts/build-desktop-server.mjs
 */
import { chmod, cp, mkdir, readFile, readdir, realpath, rm, stat, writeFile } from 'node:fs/promises';
import { stripTypeScriptTypes } from 'node:module';
import path from 'node:path';
import process from 'node:process';

const ROOT = process.cwd();
const CONTENT = path.join(ROOT, 'packages/content/dist/content-bundle.json');
const RUNTIME = path.join(ROOT, 'apps/desktop/src-tauri/server/runtime');
const BINARIES = path.join(ROOT, 'apps/desktop/src-tauri/binaries');

/** The packages the server imports at runtime. */
const PACKAGES = ['protocol', 'rules', 'server'];

/** The files/directories that are not part of a package's runtime graph. */
const EXCLUDED = new Set(['node_modules', 'dist', 'coverage', '.git']);

/** The Tauri target triple the sidecar is named for. */
function targetTriple() {
  const fromTauri = process.env['TAURI_ENV_TARGET_TRIPLE'];
  if (fromTauri) return fromTauri;
  const operatingSystem =
    process.platform === 'win32'
      ? 'pc-windows-msvc'
      : process.platform === 'darwin'
        ? 'apple-darwin'
        : 'unknown-linux-gnu';
  const architecture =
    process.arch === 'x64' ? 'x86_64' : process.arch === 'arm64' ? 'aarch64' : process.arch;
  return `${architecture}-${operatingSystem}`;
}

/** A stripped `.ts` file, with its relative imports pointing at `.mjs`. */
function transpile(source) {
  return stripTypeScriptTypes(source).replace(
    /(['"])(\.{1,2}\/[^'"]+)\.ts\1/g,
    `$1$2.mjs$1`,
  );
}

/** Copy a source tree as runnable `.mjs`, leaving tests and output behind. */
async function copySources(from, to) {
  await mkdir(to, { recursive: true });
  for (const entry of await readdir(from, { withFileTypes: true })) {
    if (EXCLUDED.has(entry.name) || entry.name.endsWith('.test.ts')) continue;
    const source = path.join(from, entry.name);
    if (entry.isDirectory()) {
      await copySources(source, path.join(to, entry.name));
    } else if (entry.isFile() && entry.name.endsWith('.ts')) {
      const code = await readFile(source, 'utf8');
      await writeFile(path.join(to, `${entry.name.slice(0, -3)}.mjs`), transpile(code), 'utf8');
    } else if (entry.isFile()) {
      await cp(source, path.join(to, entry.name));
    }
  }
}

/** A package manifest whose exports point at the stripped files. */
function manifestFor(meta) {
  const toMjs = (value) => {
    if (typeof value === 'string') return value.replace(/\.ts$/, '.mjs');
    if (value && typeof value === 'object') {
      return Object.fromEntries(Object.entries(value).map(([key, inner]) => [key, toMjs(inner)]));
    }
    return value;
  };
  return {
    name: meta.name,
    version: meta.version,
    private: true,
    type: 'module',
    exports: Object.fromEntries(
      Object.entries(meta.exports ?? { '.': './src/index.ts' }).map(([key, value]) => [
        key,
        toMjs(value),
      ]),
    ),
  };
}

/** The real directory behind a pnpm symlink. */
async function realPackage(name) {
  const target = await realpath(path.join(ROOT, 'node_modules', ...name.split('/')));
  if (!(await stat(target)).isDirectory()) throw new Error(`${name} is not a directory`);
  return target;
}

/** The generated entry: keep relative data directories rooted at the runtime. */
const START = `// Generated by scripts/build-desktop-server.mjs. Do not edit.
import { chdir } from 'node:process';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

// The server resolves its content bundle from its own module URL, so this
// chdir is only for relative data directories supplied at runtime.
chdir(dirname(fileURLToPath(import.meta.url)));
await import('./apps/server/src/main.mjs');
`;

async function main() {
  let bundle;
  try {
    bundle = JSON.parse(await readFile(CONTENT, 'utf8'));
  } catch {
    throw new Error('no content bundle. Run: pnpm build:content');
  }
  if (!Array.isArray(bundle.items) || bundle.items.length === 0) {
    throw new Error('the content bundle has no items. Run: pnpm build:content');
  }

  // A fresh tree, so a stale file from an earlier build cannot ship.
  await rm(RUNTIME, { recursive: true, force: true });
  await mkdir(RUNTIME, { recursive: true });

  // The server entry and the workspace packages it imports.
  await writeFile(
    path.join(RUNTIME, 'package.json'),
    `${JSON.stringify({ private: true, type: 'module' }, null, 2)}\n`,
  );
  await writeFile(path.join(RUNTIME, 'start.mjs'), START, 'utf8');
  await copySources(path.join(ROOT, 'apps/server/src'), path.join(RUNTIME, 'apps/server/src'));

  for (const name of PACKAGES) {
    const from = path.join(ROOT, 'packages', name);
    const to = path.join(RUNTIME, 'node_modules/@swl', name);
    await copySources(path.join(from, 'src'), path.join(to, 'src'));
    const meta = JSON.parse(await readFile(path.join(from, 'package.json'), 'utf8'));
    await writeFile(path.join(to, 'package.json'), `${JSON.stringify(manifestFor(meta), null, 2)}\n`);
  }

  // The content travels with the server: the authority and the client read
  // the same bundle by construction.
  await mkdir(path.join(RUNTIME, 'packages/content/dist'), { recursive: true });
  await cp(CONTENT, path.join(RUNTIME, 'packages/content/dist/content-bundle.json'));

  // The server's only external dependency. PGlite is Apache-2.0 and ships
  // as plain files and WASM, so a copy is enough — no native addon, no
  // install step and no network access.
  const pglite = await realPackage('@electric-sql/pglite');
  await cp(pglite, path.join(RUNTIME, 'node_modules/@electric-sql/pglite'), {
    recursive: true,
    dereference: true,
  });

  // The runtime itself, named the way Tauri expects `externalBin` to be.
  const suffix = process.platform === 'win32' ? '.exe' : '';
  const sidecar = path.join(BINARIES, `swl-server-${targetTriple()}${suffix}`);
  await mkdir(BINARIES, { recursive: true });
  await cp(process.execPath, sidecar);
  if (process.platform !== 'win32') await chmod(sidecar, 0o755);

  console.log(`built the desktop server sidecar: ${path.relative(ROOT, sidecar)}`);
  console.log(
    `bundled the server, ${bundle.items.length} content items and PGlite in ${path.relative(ROOT, RUNTIME)}`,
  );
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
